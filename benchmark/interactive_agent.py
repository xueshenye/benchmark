"""Interactive multi-turn agent (Design A+, dynamic milestones).

Subclasses Harbor's ``ClaudeCode`` installed agent and drives the whole
multi-turn interaction inside a single ``run()``:

- Round 1 uses the task's initial instruction (``instruction.md``).
- Rounds >= 2 get ONLY the simulated user's natural message (generated by a
  user-LLM from the agent's actual previous output) — no history is replayed.
  The agent must reconstruct context from the environment + the new message.
- The interaction is dynamic: the user-LLM judges whether the previous output
  satisfied the current milestone — satisfied → next milestone, unsatisfied →
  corrective feedback, past the correction budget → force-advance (the verifier
  scores that milestone 0). ``max_rounds`` caps the total.
- Each round is a fresh ``claude --print`` run over the shared environment, so
  code from earlier rounds persists in the container.

The verifier later scores every milestone's ground-truth requirement against
the final state, so an agent that only satisfies the last milestone scores low.
"""

from __future__ import annotations

import difflib
import json
import os
import shlex
from pathlib import Path

from harbor.agents.installed.claude_code import ClaudeCode
from harbor.environments.base import BaseEnvironment
from harbor.models.agent.context import AgentContext

from benchmark.controller import TurnController
from benchmark.scenario import Scenario
from benchmark.user_simulator import UserSimulator

SCENARIO_PATH_DEFAULT = "/workspace/scenario.json"
AGENT_OUTPUT_PATH = "/logs/agent/claude-code.txt"
MAX_AGENT_OUTPUT_CHARS = 6000
# Workspace evidence shown to the user-LLM so its "satisfied" judgement is
# grounded in the agent's REAL file changes, not just the agent's self-report.
MAX_WORKSPACE_EVIDENCE_CHARS = 6000
MAX_FILE_BYTES = 512 * 1024  # skip files larger than this when snapshotting


class InteractiveUserClaude(ClaudeCode):
    """Wraps claude-code to run an interactive multi-turn session with a simulated user."""

    def __init__(
        self,
        logs_dir: str | Path,
        memory_dir: str | None = None,
        *args,
        user_llm: UserSimulator.LLMCall | None = None,
        **kwargs,
    ) -> None:
        super().__init__(logs_dir, memory_dir, *args, **kwargs)
        # Injectable LLM callable for the simulated user (tests); None → Harbor LiteLLM.
        self._user_llm = user_llm

    @staticmethod
    def name() -> str:
        return "interactive-user-claude"

    def _scenario_container_path(self) -> str:
        return os.environ.get("SCENARIO_PATH", SCENARIO_PATH_DEFAULT)

    # ------------------------------------------------------------------ run

    async def run(
        self,
        instruction: str,
        environment: BaseEnvironment,
        context: AgentContext,
    ) -> None:
        scenario = await self._load_scenario(environment)

        simulator = UserSimulator(scenario, llm=self._user_llm)
        simulator.start(instruction)
        controller = TurnController(scenario, simulator)

        agent_outputs: list[str] = []
        last_agent_output = ""
        workspace_evidence = ""
        prev_snapshot = await self._gather_workspace_snapshot(environment)

        while not controller.is_done:
            user_msg = await controller.next_user_message(
                last_agent_output, instruction, workspace_evidence=workspace_evidence
            )
            if controller.should_stop_before_run:
                # All milestones are done; the terminal message must not run as a round.
                break

            milestone = controller.current_milestone
            self.logger.info(
                "Interactive round %d/%d (milestone %s): running claude-code on user message",
                controller.round_count,
                scenario.max_rounds,
                milestone.index if milestone else None,
            )
            await super().run(
                instruction=user_msg,
                environment=environment,
                context=context,
            )
            last_agent_output = await self._read_agent_output(environment)
            agent_outputs.append(last_agent_output)

            # Capture what the agent actually changed this round, so the next
            # user message is grounded in the real files, not the agent's words.
            cur_snapshot = await self._gather_workspace_snapshot(environment)
            workspace_evidence = self._workspace_diff(prev_snapshot, cur_snapshot)
            prev_snapshot = cur_snapshot

        self._write_transcript_artifact(scenario, simulator, agent_outputs, controller)

        if context.metadata is None:
            context.metadata = {}
        context.metadata["num_rounds"] = len(agent_outputs)
        context.metadata["max_rounds"] = scenario.max_rounds
        context.metadata["num_milestones"] = len(scenario.milestones)
        context.metadata["user_llm_model"] = simulator.model
        context.n_input_tokens = (context.n_input_tokens or 0) + simulator.input_tokens
        context.n_output_tokens = (context.n_output_tokens or 0) + simulator.output_tokens
        context.cost_usd = (context.cost_usd or 0.0) + simulator.cost_usd

    # ------------------------------------------------------------- helpers

    async def _load_scenario(self, environment: BaseEnvironment) -> Scenario:
        path = self._scenario_container_path()
        result = await environment.exec(command=f"cat {path}")
        if not result.stdout:
            raise RuntimeError(
                f"scenario.json not found or empty at {path} in the task environment"
            )
        return Scenario.parse(result.stdout)

    async def _read_agent_output(self, environment: BaseEnvironment) -> str:
        """Read claude-code's stream-json output from the last round and summarize it."""
        result = await environment.exec(command=f"cat {AGENT_OUTPUT_PATH}")
        summary = self._extract_agent_summary(result.stdout or "")
        return summary[:MAX_AGENT_OUTPUT_CHARS]

    async def _gather_workspace_snapshot(self, environment: BaseEnvironment) -> dict[str, str]:
        """Snapshot ``/workspace`` text files as {path: content}.

        Fed into the user-LLM's judgement so "satisfied" is grounded in the
        agent's actual file changes. Skips dot-directories (e.g. .git) and
        files over ``MAX_FILE_BYTES``.
        """
        result = await environment.exec(
            command="find /workspace -type f -printf '%p\\t%s\\n' | sort"
        )
        snapshot: dict[str, str] = {}
        for line in (result.stdout or "").splitlines():
            path, _, size_s = line.rpartition("\t")
            if not path:
                continue
            if any(seg.startswith(".") for seg in path.split("/")[2:]):
                continue
            try:
                size = int(size_s)
            except ValueError:
                continue
            if size > MAX_FILE_BYTES:
                continue
            content = await environment.exec(command=f"cat -- {shlex.quote(path)}")
            snapshot[path] = (content.stdout or "")[:MAX_FILE_BYTES]
        return snapshot

    @staticmethod
    def _workspace_diff(
        prev: dict[str, str],
        cur: dict[str, str],
        max_chars: int = MAX_WORKSPACE_EVIDENCE_CHARS,
    ) -> str:
        """Compact diff of what changed between two workspace snapshots."""
        added = sorted(cur.keys() - prev.keys())
        removed = sorted(prev.keys() - cur.keys())
        changed = sorted(k for k in cur.keys() & prev.keys() if prev[k] != cur[k])
        parts: list[str] = []
        if removed:
            parts.append("已删除: " + ", ".join(removed))
        if added:
            parts.append("新增: " + ", ".join(added))
        if changed:
            parts.append("修改: " + ", ".join(changed))
        for f in added + changed:
            before = (prev.get(f, "") or "").splitlines()
            after = (cur.get(f, "") or "").splitlines()
            parts.append(
                "\n".join(
                    difflib.unified_diff(before, after, fromfile=f, tofile=f, lineterm="", n=1)
                )
            )
        text = "\n".join(parts).strip()
        if not text:
            return "(本轮无文件改动)"
        return text[:max_chars]

    @staticmethod
    def _extract_agent_summary(stream_text: str) -> str:
        """Pull the final assistant text out of claude-code's ``--print`` stream-json."""
        if not stream_text:
            return ""
        result_text = ""
        assistant_parts: list[str] = []
        for line in stream_text.splitlines():
            line = line.strip()
            if not line or not line.startswith("{"):
                continue
            try:
                event = json.loads(line)
            except json.JSONDecodeError:
                continue
            etype = event.get("type")
            if etype == "result":
                value = event.get("result")
                if isinstance(value, str):
                    result_text = value
            elif etype == "assistant":
                message = event.get("message") or {}
                content = message.get("content")
                if isinstance(content, list):
                    for block in content:
                        if isinstance(block, dict) and block.get("type") == "text":
                            assistant_parts.append(block.get("text") or "")
                elif isinstance(content, str):
                    assistant_parts.append(content)
        return (result_text or "\n".join(assistant_parts)).strip()

    def _write_transcript_artifact(
        self,
        scenario: Scenario,
        simulator: UserSimulator,
        agent_outputs: list[str],
        controller: TurnController,
    ) -> None:
        artifact = {
            "scenario": scenario.model_dump(),
            "num_rounds": len(agent_outputs),
            "max_rounds": scenario.max_rounds,
            "max_corrections": scenario.max_corrections,
            "transcript": simulator.transcript,
            "agent_outputs": agent_outputs,
            "decisions": controller.decisions,
        }
        path = Path(self.logs_dir) / "interactive_transcript.json"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(artifact, ensure_ascii=False, indent=2), encoding="utf-8")
