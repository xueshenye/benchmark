"""InteractiveMultiStepTrial: Design B's native multi-step driver.

Subclasses Harbor's ``MultiStepTrial`` so each step = one interaction round.
Between steps it reads the just-archived agent output + workspace snapshot,
asks the user-LLM to judge and speak (via ``StepDriver``), and injects the next
step's instruction through a wrapped ``Task.step_instruction`` — so nothing is
written into the task directory (a local ``-p`` task is used in place).

Design decisions (see PROJECT_STATE §8):
- ``multi_step_reward_strategy="final"`` → the trial reward is the last step's
  full-milestone product, identical to Design A+'s discriminator.
- ``min_reward`` is left unset: a corrective round legitimately scores low, and
  aborting on it would break the correction loop. Termination is governed by the
  ``TurnController`` (all milestones done / round budget spent), which triggers
  an early break via ``_done_early``.
"""

from __future__ import annotations

import json
from typing import override

from harbor.models.trial.result import StepResult
from harbor.trial.multi_step import MultiStepTrial

from benchmark.controller import TurnController
from benchmark.scenario import Scenario
from benchmark.step_driver import StepDriver
from benchmark.user_simulator import UserSimulator


class InteractiveMultiStepTrial(MultiStepTrial):
    """Native multi-step trial whose step instructions are generated by the user-LLM."""

    def __init__(
        self,
        config,
        *,
        _task=None,
        _task_download_result,
        user_llm: UserSimulator.LLMCall | None = None,
    ) -> None:
        super().__init__(
            config,
            _task=_task,
            _task_download_result=_task_download_result,
        )

        scenario_path = self.task.paths.task_dir / "environment" / "scenario.json"
        scenario = Scenario.load(scenario_path)

        simulator = UserSimulator(scenario, llm=user_llm)
        controller = TurnController(scenario, simulator)
        self.driver = StepDriver(scenario, simulator, controller)

        self._done_early = False
        self._generated: dict[str, str] = {}
        self._agent_outputs: list[str] = []

        # Inject generated step instructions via a wrapped Task.step_instruction
        # (lazy-read per step) instead of rewriting steps/{name}/instruction.md.
        original_step_instruction = self.task.step_instruction

        def _step_instruction(step_name: str) -> str:
            return self._generated.get(step_name) or original_step_instruction(step_name)

        self.task.step_instruction = _step_instruction  # type: ignore[method-assign]

        first_step = (self.task.config.steps or [])[0]
        self._first_instruction = self.task.step_instruction(first_step.name)
        self.driver.on_step_started(self._first_instruction)

    @override
    async def _run(self) -> None:
        # Mirrors MultiStepTrial._run with an additional early-break on
        # controller completion (avoids trailing no-op steps).
        self.result.step_results = []

        steps = self.task.config.steps or []
        for index, step in enumerate(steps, start=1):
            step_result = StepResult(step_name=step.name)
            self.result.step_results.append(step_result)

            await self._run_step(
                step,
                step_result,
                index=index,
                total=len(steps),
            )

            if self._should_stop_after_step(step, step_result) or self._done_early:
                self._move_agent_dir_to_step(step)
                break

        self.result.verifier_result = self._select_multi_step_reward()

        await self._stop_agent_environment()

        self.paths.cleanup_empty_mount_dirs()

    @override
    async def _run_step(self, step, step_result, *, index, total) -> None:
        await super()._run_step(step, step_result, index=index, total=total)
        await self._after_step(step, step_result, index=index, total=total)

    async def _after_step(self, step, step_result, *, index, total) -> None:
        """Between-step: read the just-archived outputs, judge, and prepare the
        next step's instruction."""
        if step_result.exception_info is not None:
            return

        step_dir = self.paths.step_agent_dir(step.name)
        summary_path = step_dir / "agent_summary.txt"
        snapshot_path = step_dir / "workspace_snapshot.json"
        agent_output = (
            summary_path.read_text(encoding="utf-8") if summary_path.exists() else ""
        )
        snapshot: dict[str, str] = {}
        if snapshot_path.exists():
            try:
                snapshot = json.loads(snapshot_path.read_text(encoding="utf-8"))
            except json.JSONDecodeError:
                snapshot = {}
        self._agent_outputs.append(agent_output)

        next_instruction = await self.driver.on_step_completed(agent_output, snapshot)

        if next_instruction and index < total:
            next_name = self.task.config.steps[index].name
            self._generated[next_name] = next_instruction
        if self.driver.is_done:
            self._done_early = True

        self._write_transcript()

    def _write_transcript(self) -> None:
        artifact = {
            "scenario": self.driver.scenario.model_dump(),
            "num_rounds": len(self._agent_outputs),
            "max_rounds": self.driver.scenario.max_rounds,
            "max_corrections": self.driver.scenario.max_corrections,
            "transcript": self.driver.simulator.transcript,
            "agent_outputs": self._agent_outputs,
            "decisions": self.driver.controller.decisions,
        }
        path = self.paths.trial_dir / "interactive_transcript.json"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            json.dumps(artifact, ensure_ascii=False, indent=2), encoding="utf-8"
        )
